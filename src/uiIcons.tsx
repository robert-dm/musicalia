export function ContextMenuItem({
  icon,
  label,
  shortcut,
  danger,
  disabled,
  onClick
}: {
  icon: ReactNode
  label: string
  shortcut?: string
  danger?: boolean
  disabled?: boolean
  onClick: () => void
}) {
  return (
    <button
      type="button"
      className={`context-menu-item${danger ? ' danger' : ''}${disabled ? ' disabled' : ''}`}
      disabled={disabled}
      onClick={onClick}
    >
      <span className="context-menu-icon">{icon}</span>
      <span className="context-menu-label">{label}</span>
      {shortcut ? <span className="context-menu-kbd">{shortcut}</span> : null}
    </button>
  )
}
